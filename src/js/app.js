function parseCSV(csv) {
    const lines = csv.trim().split('\n').filter(l => l.trim().length > 0);
    const headers = lines[0].split(',');
    const data = {};

    // Init vehicle buckets
    VEHICLES.forEach(v => { data[v.plate] = { days: {} }; });

    for (let i = 1; i < lines.length; i++) {
        const values = smartSplitCSV(lines[i]);
        if (values.length < 35) continue;

        const plate = (values[2] || '').trim();
        const km = parseInt((values[3] || '0').replace(/\D/g, '')) || 0;
        const driver = (values[4] || '').trim();
        const rawDate = (values[6] || '').trim(); // DD/MM/YYYY
        const comment = (values[39] || '').trim();

        if (!data[plate]) continue;

        // Parse date to YYYY-MM-DD
        const dateParts = rawDate.split('/');
        if (dateParts.length !== 3) continue;
        let [dd, mm, yyyy] = dateParts;
        // Fix typos in year (e.g., 0026 → 2026)
        if (yyyy.length === 4 && parseInt(yyyy) < 100) yyyy = '2026';
        if (yyyy === '2025') yyyy = '2026'; // fix obvious typo
        const dateStr = `${yyyy}-${mm.padStart(2, '0')}-${dd.padStart(2, '0')}`;

        // Parse question answers (columns 8-36, 29 questions)
        const answers = {};
        QUESTIONS.forEach((q, qi) => {
            const val = (values[8 + qi] || '').trim();
            answers[q] = (val === 'OK' || val === 'NOK') ? val : 'OK';
        });

        // If same plate+date already exists, keep the one with more NOKs or merge
        const existing = data[plate].days[dateStr];
        if (existing) {
            // Merge: keep NOK if either entry has NOK
            QUESTIONS.forEach(q => {
                if (answers[q] === 'NOK') existing.questions[q] = 'NOK';
            });
            if (comment && comment.length > 2) {
                if (existing.comment) {
                    existing.comment += ' | ' + comment;
                } else {
                    existing.comment = comment;
                }
            }
            if (km > existing.km) existing.km = km;
        } else {
            data[plate].days[dateStr] = {
                km: km,
                driver: driver,
                questions: answers,
                comment: (comment && comment.length > 2) ? comment : null
            };
        }
    }

    return data;
}

function smartSplitCSV(line) {
    const result = [];
    let current = '';
    let inQuotes = false;

    for (let i = 0; i < line.length; i++) {
        const ch = line[i];
        if (ch === '"') {
            inQuotes = !inQuotes;
        } else if (ch === ',' && !inQuotes) {
            result.push(current);
            current = '';
        } else {
            current += ch;
        }
    }
    result.push(current);
    return result;
}

// ─── NLP: RECURRENCE DETECTION ─────────────
function tokenize(text) {
    return text
        .toLowerCase()
        .normalize('NFD')
        .replace(/[\u0300-\u036f]/g, '')
        .replace(/[^a-z0-9\s]/g, '')
        .split(/\s+/)
        .filter(w => w.length > 2 && !PT_STOPWORDS.has(w));
}

function jaccardSimilarity(tokensA, tokensB) {
    const setA = new Set(tokensA);
    const setB = new Set(tokensB);
    const intersection = new Set([...setA].filter(x => setB.has(x)));
    const union = new Set([...setA, ...setB]);
    return union.size > 0 ? intersection.size / union.size : 0;
}

function detectRecurrences(vehicleDays, threshold = 0.25) {
    const comments = [];
    Object.entries(vehicleDays).forEach(([date, dayData]) => {
        if (dayData.comment && dayData.comment.trim().length > 3) {
            const lower = dayData.comment.toLowerCase();
            // Skip generic non-issue comments
            if (/^(não|nao|sim|ok)$/i.test(lower.trim())) return;
            comments.push({
                date,
                text: dayData.comment,
                tokens: tokenize(dayData.comment)
            });
        }
    });

    if (comments.length < 2) return [];

    const parent = comments.map((_, i) => i);
    function find(x) { return parent[x] === x ? x : (parent[x] = find(parent[x])); }
    function unite(a, b) { parent[find(a)] = find(b); }

    for (let i = 0; i < comments.length; i++) {
        for (let j = i + 1; j < comments.length; j++) {
            const sim = jaccardSimilarity(comments[i].tokens, comments[j].tokens);
            if (sim >= threshold) {
                unite(i, j);
            }
        }
    }

    const clusters = {};
    comments.forEach((c, i) => {
        const root = find(i);
        if (!clusters[root]) clusters[root] = [];
        clusters[root].push(c);
    });

    const recurrences = [];
    Object.values(clusters).forEach(group => {
        if (group.length >= 2) {
            const allTokens = group.flatMap(g => g.tokens);
            const freq = {};
            allTokens.forEach(t => { freq[t] = (freq[t] || 0) + 1; });
            const theme = Object.entries(freq)
                .filter(([, count]) => count >= 2)
                .sort((a, b) => b[1] - a[1])
                .slice(0, 4)
                .map(([word]) => word.charAt(0).toUpperCase() + word.slice(1))
                .join(', ');

            let totalSim = 0;
            let pairs = 0;
            for (let i = 0; i < group.length; i++) {
                for (let j = i + 1; j < group.length; j++) {
                    totalSim += jaccardSimilarity(group[i].tokens, group[j].tokens);
                    pairs++;
                }
            }

            recurrences.push({
                theme: theme || 'Relato recorrente',
                count: group.length,
                avgSimilarity: pairs > 0 ? Math.round((totalSim / pairs) * 100) : 0,
                items: group.sort((a, b) => a.date.localeCompare(b.date))
            });
        }
    });

    return recurrences.sort((a, b) => b.count - a.count);
}

